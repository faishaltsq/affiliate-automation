    writer_mod._affiliate_locked = lambda: False

    results = run_30_drafts()

    out_json = REPO_ROOT / "docs" / "v2" / "sol_conversational_30_drafts.json"
    out_md = REPO_ROOT / "docs" / "v2" / "sol_conversational_30_drafts.md"
