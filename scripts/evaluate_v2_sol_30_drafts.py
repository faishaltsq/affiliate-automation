# ── Live client ─────────────────────────────────────────────────────────────
def _get_live_client() -> HttpLLMClient:
    """Return the configured client, or the local 9router gateway if it 403s."""
    try:
        primary = HttpLLMClient()
        primary.complete([{"role": "user", "content": "ping"}], max_tokens=5)
        print("Using primary LLM endpoint:", primary.config.base_url,
              f"({primary.config.model})")
        return primary
    except Exception as exc:  # noqa: BLE001
        print(f"Primary endpoint unavailable ({type(exc).__name__}). "
              "Falling back to local 9router gateway...")
        api_key = (
            os.getenv("HERMES_CUSTOM_LOCALHOST_20128_API_KEY")
            or os.getenv("LLM_API_KEY")
            or "local-secret"
        )
        cfg = LLMConfig(
            base_url="http://localhost:20128/v1",
            model="opusantigravity",
            fallback_models=["opusantigravity"],
            api_key=api_key,
            timeout_seconds=120,
        )
        fallback = HttpLLMClient(config=cfg)
        fallback.complete([{"role": "user", "content": "ping"}], max_tokens=5)
        print("Using 9Router LLM endpoint: http://localhost:20128/v1 (opusantigravity)")
        return fallback


# ── Naturalness metrics ─────────────────────────────────────────────────────
_EMOJI_RE = re.compile(
    "[\U0001F300-\U0001FAFF\U00002600-\U000027BF\U0001F1E6-\U0001F1FF]"
)
_SENTENCE_RE = re.compile(r"[.!?]+(?:\s|$)")


def text_metrics(text: str) -> dict:
    """Cheap, deterministic shape metrics for the side-by-side report."""
    text = (text or "").strip()
    words = [w for w in re.split(r"\s+", text) if w]
    sentence_count = max(1, len(_SENTENCE_RE.findall(text))) if text else 0
    paragraphs = [p for p in text.split("\n\n") if p.strip()]
    return {
        "word_count": len(words),
        "sentence_count": sentence_count,
        "paragraph_count": len(paragraphs),
        "avg_words_per_sentence": (
            round(len(words) / sentence_count, 1) if sentence_count else 0.0
        ),
        "emoji_count": len(_EMOJI_RE.findall(text)),
        "has_bullet_or_numbered_list": bool(
            re.search(r"^\s*(?:[-*•]|\d+[.)])\s+", text, re.M)
        ),
    }


def _findings_list(evaluation) -> list[dict]:
    return [
        asdict(f) if hasattr(f, "__dataclass_fields__") else f
        for f in getattr(evaluation, "findings", [])
    ]


# ── One draft ───────────────────────────────────────────────────────────────
def _process_one_draft(idx: int, spec: dict, client, base_data_dir: Path) -> dict:
    db_path = base_data_dir / f"sol_worker_{idx}.db"
    if db_path.exists():
        db_path.unlink()
    migrate(db_path)

    category = spec["category"]
    pillar = spec["pillar"]
    problem = spec["audience_problem"]
    angle = spec["angle"]
    evidence = spec.get("evidence", "")
    is_affiliate = category == "affiliate"
    persona = get_sol_persona()

    print(f"[{idx}/30 START] {category} | {angle}")

    idea = IdeaCandidate(
        pillar=pillar,
        angle=angle,
        audience_problem=problem,
        observation=spec.get("observation", ""),
        delivery_hint=spec.get("delivery_hint", ""),
    )

    t_start = time.time()
    draft = write_draft(
        pillar=pillar,
        idea=idea,
        evidence=evidence,
        client=client,
        path=db_path,
        persist=True,
        persona=persona,
    )

    if draft is None:
        print(f"[{idx}/30 ERROR] write_draft returned None")
        return {
            "index": idx,
            "category": category,
            "pillar": pillar,
            "audience_problem": problem,
            "angle": angle,
            "observation": spec.get("observation", ""),
            "delivery_hint": spec.get("delivery_hint", ""),
            "format_hint": spec.get("format_hint", ""),
            "actual_format": "",
            "is_affiliate": is_affiliate,
            "evidence": evidence,
            "original_draft": "",
            "cleaned_draft": "",
            "disclosure_was_present": False,
            "disclosure_appended": False,
            "editorial_edits": [],
            "had_editorial_changes": False,
            "stage1_evaluation": {"score": 0, "verdict": REJECTED, "findings": [],
                                  "concerns": [], "notes": "Generation failed"},
            "rewritten_draft": None,
            "final_evaluation": {"content": "", "score": 0, "verdict": REJECTED,
                                 "findings": [], "concerns": [],
                                 "notes": "Generation failed"},
            "metrics_original": text_metrics(""),
            "metrics_final": text_metrics(""),
            "duration_seconds": round(time.time() - t_start, 2),
        }

    orig_content = draft.raw_content or draft.content
    cleaned_content = draft.content
    applied_edits = getattr(draft, "applied_edits", [])
    actual_format = (draft.variation or {}).get("format", spec.get("format_hint", ""))

    disclosure_present = has_disclosure(cleaned_content) or has_disclosure(
        getattr(draft, "disclosure", "")
    )
    disclosure_appended = False
    if is_affiliate and not disclosure_present:
        cleaned_content = ensure_disclosure(cleaned_content, short=True)
        disclosure_appended = True
        disclosure_present = True

    eval1 = evaluate_draft(
        cleaned_content,
        evidence=evidence,
        pillar=pillar,
        parts=draft.parts,
        draft_id=draft.draft_id,
        client=client,
        path=db_path,
        persist=True,
        format_name=actual_format,
        is_affiliate=is_affiliate,
        affiliate_verified=is_affiliate,
        has_disclosure=disclosure_present,
        persona=persona,
    )

    findings1 = _findings_list(eval1)
    concerns1 = list(getattr(eval1, "concerns", []))
    notes1 = getattr(eval1, "notes", "")
    score1 = getattr(eval1, "total_score", 0.0)
    verdict1 = getattr(eval1, "verdict", REJECTED)

    print(f"[{idx}/30 STAGE1] {verdict1} ({score1}) | findings={len(findings1)}")

    rewritten = None
    final_content = cleaned_content
    final_verdict, final_score = verdict1, score1
    final_findings, final_concerns, final_notes = findings1, concerns1, notes1

    if verdict1 == REVISE_ONCE:
        print(f"[{idx}/30 REWRITE] revision pass...")
        feedback_items = [
            f"[{f.get('severity', '')}] {f.get('code', '')}: "
            f"'{f.get('evidence', '')}' -> Saran: {f.get('suggested_fix', '')}"
            for f in findings1
        ]
        if not feedback_items and concerns1:
            feedback_items.extend(concerns1)
        feedback_str = "\n".join(feedback_items)

        draft2 = write_draft(
            pillar=pillar,
            idea=idea,
            evidence=evidence,
            revision_feedback=feedback_str,
            client=client,
            path=db_path,
            persist=True,
            persona=persona,
        )
        if draft2:
            rewritten = {
                "raw_content": draft2.raw_content or draft2.content,
                "cleaned_content": draft2.content,
                "applied_edits": getattr(draft2, "applied_edits", []),
                "actual_format": (draft2.variation or {}).get("format", actual_format),
            }
            rewrite_content = draft2.content
            if is_affiliate and not has_disclosure(rewrite_content):
                rewrite_content = ensure_disclosure(rewrite_content, short=True)
                rewritten["cleaned_content"] = rewrite_content

            eval2 = evaluate_draft(
                rewrite_content,
                evidence=evidence,
                pillar=pillar,
                parts=draft2.parts,
                draft_id=draft2.draft_id,
                client=client,
                path=db_path,
                persist=True,
                format_name=rewritten["actual_format"],
                is_affiliate=is_affiliate,
                affiliate_verified=is_affiliate,
                has_disclosure=has_disclosure(rewrite_content),
                persona=persona,
            )
            final_content = rewrite_content
            final_verdict = getattr(eval2, "verdict", REJECTED)
            final_score = getattr(eval2, "total_score", 0.0)
            final_findings = _findings_list(eval2)
            final_concerns = list(getattr(eval2, "concerns", []))
            final_notes = getattr(eval2, "notes", "")
            print(f"[{idx}/30 REWRITE DONE] {final_verdict} ({final_score})")

    duration = round(time.time() - t_start, 2)
    print(f"[{idx}/30 COMPLETED] {final_verdict} ({final_score}) in {duration}s")

    return {
        "index": idx,
        "category": category,
        "pillar": pillar,
        "audience_problem": problem,
        "angle": angle,
        "observation": spec.get("observation", ""),
        "delivery_hint": spec.get("delivery_hint", ""),
        "format_hint": spec.get("format_hint", ""),
        "actual_format": actual_format,
        "is_affiliate": is_affiliate,
        "evidence": evidence,
        "original_draft": orig_content,
        "cleaned_draft": cleaned_content,
        "disclosure_was_present": disclosure_present and not disclosure_appended,
        "disclosure_appended": disclosure_appended,
        "editorial_edits": applied_edits,
        "had_editorial_changes": bool(applied_edits) or orig_content != cleaned_content,
        "stage1_evaluation": {
            "score": score1,
            "verdict": verdict1,
            "findings": findings1,
            "concerns": concerns1,
            "notes": notes1,
        },
        "rewritten_draft": rewritten,
        "final_evaluation": {
            "content": final_content,
            "score": final_score,
            "verdict": final_verdict,
            "findings": final_findings,
            "concerns": final_concerns,
            "notes": final_notes,
        },
        "metrics_original": text_metrics(orig_content),
        "metrics_final": text_metrics(final_content),
        "duration_seconds": duration,
    }


def run_30_drafts() -> list[dict]:
    from concurrent.futures import ThreadPoolExecutor, as_completed

    base_data_dir = REPO_ROOT / "data" / "workers_eval"
    base_data_dir.mkdir(parents=True, exist_ok=True)

    client = _get_live_client()
    results: list[dict] = []

    print(f"\nGenerating {len(DRAFT_SPECIFICATIONS)} drafts across "
          f"{len(CATEGORIES)} categories (max_workers=5)...")
    t0 = time.time()

    with ThreadPoolExecutor(max_workers=5) as executor:
        futures = {
            executor.submit(_process_one_draft, idx, spec, client, base_data_dir): idx
            for idx, spec in enumerate(DRAFT_SPECIFICATIONS, 1)
        }
        for fut in as_completed(futures):
            idx = futures[fut]
            try:
                results.append(fut.result())
            except Exception as exc:  # noqa: BLE001
                print(f"[ERROR] Draft #{idx} failed: {type(exc).__name__}: {exc}")

    results.sort(key=lambda r: r["index"])
    print(f"\nAll 30 drafts finished in {round(time.time() - t0, 2)}s.")
    return results


